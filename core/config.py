# 7. 多跳推理：关系传递规则与路径白名单
#
# 当直接关系不存在时，系统可查找 A→B→C 的多跳路径做间接推理。
# 本段仅定义"哪些关系组合可传递、如何标注"，不包含查询实现逻辑。
# 约定：
#   - 所有未出现在 TRANSITIVE_RULES 中的关系组合默认不允许传递。
#   - "表现为 → 导致"、"诊断于"、"治疗于" 不参与多跳路径的中间环节。
#   - ALLOWED_PATH_RELATION_TYPES 为允许出现在多跳路径（含首尾）的关系类型白名单。
# ---------------------------------------------------------------------------
# 关系组合（首跳关系类型, 次跳关系类型）→ 传递规则。
#   allowed: 是否允许该组合传递。
#   label:   间接推理时用于描述 A 与 C 之间关系的标签。
#   downgrade: 可选，True 表示结论置信度应降级（仅作弱关联参考）。
TRANSITIVE_RULES: dict[tuple[str, str], dict] = {
    ("导致", "导致"): {"allowed": True, "label": "间接导致"},
    ("导致", "表现为"): {"allowed": True, "label": "间接表现为"},
    ("导致", "影响"): {"allowed": True, "label": "间接影响"},
    ("影响", "导致"): {"allowed": True, "label": "间接影响"},
    ("影响", "表现为"): {"allowed": True, "label": "间接相关"},
    ("表现为", "表现为"): {"allowed": True, "label": "间接表现", "downgrade": True},
}

# 允许参与多跳路径的关系类型白名单（中间环节仅限这些类型）。
ALLOWED_PATH_RELATION_TYPES: set[str] = {"导致", "影响", "表现为"}

